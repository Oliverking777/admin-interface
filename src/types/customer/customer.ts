/** An individual is a person, a business is a company. A business must have a phone number. */
export type CustomerType = "INDIVIDUAL" | "BUSINESS";

/** An inactive customer can no longer be used for new operations (e.g. sales). */
export type CustomerStatus = "ACTIVE" | "INACTIVE";

/** Limits that match the backend (Customer, CustomerName and Email). */
export const CUSTOMER_NAME_MAX_LENGTH = 150;
export const CUSTOMER_EMAIL_MAX_LENGTH = 150;
export const CUSTOMER_ADDRESS_MAX_LENGTH = 300;

/**
 * Phone format: 8-15 digits with an optional leading "+".
 * The backend trims the value and strips everything except digits (and a leading "+"),
 * so test it after `normalizeCustomerPhone`.
 */
export const CUSTOMER_PHONE_PATTERN = /^\+?\d{8,15}$/;

/**
 * Email format. The backend trims the email and stores it in lower case,
 * so test it after `.trim().toLowerCase()`.
 */
export const CUSTOMER_EMAIL_PATTERN = /^[^@\s]+@[^@\s]+\.[^@\s]+$/;

/** Same normalisation as the backend PhoneNumber: keep digits and a leading "+". */
export function normalizeCustomerPhone(value: string): string {
  const trimmed = value.trim();
  return trimmed.startsWith("+")
    ? "+" + trimmed.slice(1).replace(/\D/g, "")
    : trimmed.replace(/\D/g, "");
}

/** What customer dropdowns need (e.g. choosing the customer of a sale). */
export type CustomerOption = {
  id: string;
  /** Unique, e.g. "CUS-000001". */
  code: string;
  name: string;
};

/** Frontend representation of a customer (what the UI works with). */
export type Customer = {
  id: string;
  /** Unique, generated by the backend, e.g. "CUS-000001". Never changes. */
  code: string;
  /** Max 150 characters. */
  name: string;
  /** Normalised by the backend (digits and optional leading "+"). Null when not set. */
  phone: string | null;
  /** Stored in lower case. Max 150 characters. Null when not set. */
  email: string | null;
  /** Max 300 characters. Null when not set. */
  address: string | null;
  /** Chosen at creation, never changes. */
  type: CustomerType;
  status: CustomerStatus;
  /**
   * True for the built-in walk-in (anonymous) customer.
   * It is protected: it cannot be edited or deactivated.
   */
  walkIn: boolean;
  /** ISO date-time. */
  createdAt: string;
  /** ISO date-time. */
  updatedAt: string;
};