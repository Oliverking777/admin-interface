/** An inactive supplier can no longer be used for new operations (e.g. purchases). */
export type SupplierStatus = "ACTIVE" | "INACTIVE";

/** Limits that match the backend (Supplier, SupplierName and Email). */
export const SUPPLIER_NAME_MAX_LENGTH = 150;
export const SUPPLIER_CONTACT_PERSON_MAX_LENGTH = 100;
export const SUPPLIER_EMAIL_MAX_LENGTH = 150;
export const SUPPLIER_ADDRESS_MAX_LENGTH = 300;

/**
 * Phone format: 8-15 digits with an optional leading "+".
 * The backend trims the value and strips everything except digits (and a leading "+"),
 * so test it after `normalizeSupplierPhone`.
 */
export const SUPPLIER_PHONE_PATTERN = /^\+?\d{8,15}$/;

/**
 * Email format. The backend trims the email and stores it in lower case,
 * so test it after `.trim().toLowerCase()`.
 */
export const SUPPLIER_EMAIL_PATTERN = /^[^@\s]+@[^@\s]+\.[^@\s]+$/;

/** Same normalisation as the backend PhoneNumber: keep digits and a leading "+". */
export function normalizeSupplierPhone(value: string): string {
  const trimmed = value.trim();
  return trimmed.startsWith("+")
    ? "+" + trimmed.slice(1).replace(/\D/g, "")
    : trimmed.replace(/\D/g, "");
}

/** What supplier dropdowns need (e.g. choosing the supplier of a purchase). */
export type SupplierOption = {
  id: string;
  /** Unique, e.g. "SUP-000001". */
  code: string;
  name: string;
};

/** Frontend representation of a supplier (what the UI works with). */
export type Supplier = {
  id: string;
  /** Unique, generated by the backend, e.g. "SUP-000001". Never changes. */
  code: string;
  /** Unique. Max 150 characters. */
  name: string;
  /** Who to talk to at the supplier. Max 100 characters. Null when not set. */
  contactPerson: string | null;
  /** Normalised by the backend (digits and optional leading "+"). Null when not set. */
  phone: string | null;
  /** Stored in lower case. Max 150 characters. Null when not set. */
  email: string | null;
  /** Max 300 characters. Null when not set. */
  address: string | null;
  status: SupplierStatus;
  /** ISO date-time. */
  createdAt: string;
  /** ISO date-time. */
  updatedAt: string;
};