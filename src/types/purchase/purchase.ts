/**
 * A purchase from a supplier. Created as SUBMITTED (ordered, waiting for the goods), then either CONFIRMED
 * (the delivery was recorded and the accepted goods went into stock) or CANCELLED. Mirrors PurchaseStatus.
 */
export type PurchaseStatus = "SUBMITTED" | "CONFIRMED" | "CANCELLED";

export type RejectionType = "DAMAGED" | "WRONG_PRODUCT" | "EXCESS" | "OTHER";

/** Limits that match the backend (Purchase, PurchaseItem, Text). */
export const PURCHASE_MAX_LINES = 100;
export const PURCHASE_NOTE_MAX_LENGTH = 500;
export const DELIVERY_NOTE_MAX_LENGTH = 50;
/** Cancel reason and the reason on a delivered line that differs from the order: 5-500 characters. */
export const REASON_MIN_LENGTH = 5;
export const REASON_MAX_LENGTH = 500;

/** Only a SUBMITTED purchase can be changed, delivered or cancelled. */
export const isPurchaseOpen = (s: PurchaseStatus) => s === "SUBMITTED";

/** What purchase dropdowns need. */
export type PurchaseOption = {
  id: string;
  /** Unique, e.g. "PUR-000001". */
  code: string;
  supplierName: string;
};

/**
 * A line of a purchase. Price and conversion factor are snapshots.
 * The delivery fields are null until the purchase is CONFIRMED.
 */
export type PurchaseItem = {
  id: string;
  productId: string;
  /** Null when the product can no longer be found in the catalog. */
  productName: string | null;
  unitId: string;
  /** Base units per purchase unit. At least 1. */
  conversionFactor: number;
  orderedQuantity: number;
  /** Whole FCFA, greater than 0. */
  unitPurchasePrice: number;
  /** unitPurchasePrice x orderedQuantity (whole FCFA). */
  lineTotal: number;
  /** Went into stock. */
  acceptedQuantity: number | null;
  /** Refused at delivery. */
  rejectedQuantity: number | null;
  /** Ordered and never delivered: ordered - accepted - rejected, never below 0. */
  missingQuantity: number | null;
  /** Why goods were refused, when some were. */
  rejectionType: RejectionType | null;
  /** Set when the line differs from the order. */
  discrepancyReason: string | null;
};

/** A product ordered from a supplier. */
export type SupplierProduct = {
  productId: string;
  productName: string | null;
};

/** Frontend representation of a purchase. */
export type Purchase = {
  id: string;
  /** Unique, generated by the backend, e.g. "PUR-000001". Never changes. */
  code: string;
  supplierId: string;
  /** Null when the supplier can no longer be found. */
  supplierName: string | null;
  destinationLocationId: string;
  locationName: string | null;
  status: PurchaseStatus;
  /** CONFIRMED with goods rejected or missing. */
  hasDiscrepancy: boolean;
  items: PurchaseItem[];
  /** Sum of every line total (whole FCFA). */
  totalAmount: number;
  /** ISO date (YYYY-MM-DD). Null when not set. */
  expectedDeliveryDate: string | null;
  /** Max 500 characters. Null when not set. */
  note: string | null;
  /** The supplier's delivery note number, set when the delivery is confirmed. */
  deliveryNote: string | null;
  createdBy: string;
  confirmedBy: string | null;
  cancelledBy: string | null;
  cancelReason: string | null;
  /** When it was ordered. */
  createdAt: string;
  /** When the delivery was confirmed. */
  confirmedAt: string | null;
  cancelledAt: string | null;
  updatedAt: string;
};