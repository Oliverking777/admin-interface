/** A location is either a warehouse or a store. */
export type LocationType = "WAREHOUSE" | "STORE";

/** An inactive location is not operational, but its user assignments are kept. */
export type LocationStatus = "ACTIVE" | "INACTIVE";

/** Limits that match the backend (Location). */
export const LOCATION_NAME_MAX_LENGTH = 150;
export const LOCATION_ADDRESS_MAX_LENGTH = 500;

/** What location dropdowns need (e.g. choosing where a transfer goes). */
export type LocationOption = {
  id: string;
  name: string;
};

/** Frontend representation of a location (what the UI works with). */
export type Location = {
  id: string;
  /** Generated by the backend when the location is created (LOC-0001, LOC-0002...). Unique, never changes. */
  code: string;
  /** Max 150 characters. */
  name: string;
  type: LocationType;
  /** Max 500 characters. Null when no address was given. */
  address: string | null;
  status: LocationStatus;
  /** ISO date-time. */
  createdAt: string;
  /** ISO date-time. */
  updatedAt: string;
};

/** A user assigned to a location. A user belongs to at most one location. */
export type LocationUser = {
  id: string;
  /** First and last name together. */
  name: string;
  /** Login name, e.g. "john.doe". */
  userName: string;
  /** Display name of the user's role, as stored by the backend (upper case, e.g. "MANAGER"). */
  roleName: string;
  /** False when the user's account is deactivated. */
  active: boolean;
  /** ISO date-time. */
  assignedAt: string;
};