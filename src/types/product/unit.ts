/**
 * An inactive unit cannot be assigned to products any more.
 * Products that already use it keep working: deactivating only blocks new assignments.
 */
export type UnitStatus = "ACTIVE" | "INACTIVE";

/** Limit that matches the backend (UnitName). The code is generated, so it has no form rule. */
export const UNIT_NAME_MAX_LENGTH = 50;

/** What unit dropdowns need (e.g. choosing the unit to assign to a product). */
export type UnitOption = {
  id: string;
  /** Unique, e.g. "U0003" (older units may have a typed code such as "CTN"). */
  code: string;
  /** e.g. "Carton". */
  name: string;
};

/** Frontend representation of a unit of measure (what the UI works with). */
export type Unit = {
  id: string;
  /** Generated by the backend (U0001, U0002...); older units may have a typed code such as "CTN". Never changes. */
  code: string;
  /** Unique ignoring case. Max 50 characters. */
  name: string;
  status: UnitStatus;
  /** ISO date-time. */
  createdAt: string;
  /** ISO date-time. */
  updatedAt: string;
};