/**
 * IAM models.
 *
 * Field names match the backend JSON exactly, so mapping from a DTO is trivial.
 * Conventions for data coming from the Spring Boot API:
 *  - UUID    -> string
 *  - Instant -> ISO-8601 string (e.g. "2026-09-30T22:15:30Z")
 *
 * No UI-specific fields belong in this file.
 */

/** UUID serialized as a string. */
export type UUID = string;

/** ISO-8601 date-time string (backend `Instant`, always UTC). */
export type ISODateTime = string;

/**
 * Where the users of a role work.
 * ALL: across every location, no location assignment needed (e.g. the owner).
 * ASSIGNED: each user must belong to exactly one location.
 */
export const LocationScope = {
  ALL: "ALL",
  ASSIGNED: "ASSIGNED",
} as const;

export type LocationScope = (typeof LocationScope)[keyof typeof LocationScope];

/* -------------------------------------------------------------------------- */
/*  Permission                                                                */
/* -------------------------------------------------------------------------- */

export interface Permission {
  permissionId: UUID;
  /** Upper-case code, e.g. "ROLE_CREATE". */
  permissionCode: string;
  createdAt: ISODateTime;
}

/* -------------------------------------------------------------------------- */
/*  Role                                                                      */
/* -------------------------------------------------------------------------- */

export interface Role {
  roleId: UUID;
  /** Upper-case name, e.g. "ADMIN". */
  roleName: string;
  /** Max 255 characters. Null when no description is set. */
  description: string | null;
  locationScope: LocationScope;
  /** True for built-in roles: they cannot be renamed, deleted or given another scope. */
  system: boolean;
  createdAt: ISODateTime;
  updatedAt: ISODateTime;
}

/** A role together with the permissions it grants. */
export interface RolePermissions {
  roleId: UUID;
  roleName: string;
  /** Ordered by permission code. */
  permissions: Permission[];
}

/* -------------------------------------------------------------------------- */
/*  User                                                                      */
/* -------------------------------------------------------------------------- */

/**
 * A user of the system. Never contains password data.
 * A user has exactly one role, referenced by id.
 */
export interface User {
  userId: UUID;
  firstName: string;
  lastName: string;
  /** Always `firstName + " " + lastName`, maintained by the backend. */
  fullName: string;
  /** Generated by the backend at creation; never changes. */
  userName: string;
  roleId: UUID;
  /** False when the account is deactivated and cannot log in. */
  active: boolean;
  createdAt: ISODateTime;
  updatedAt: ISODateTime;
}

/**
 * The logged-in user: who they are and what they may do.
 * Built from the "current user" endpoint (it carries no first/last name or timestamps),
 * plus the user's location from the Location module.
 */
export interface AuthenticatedUser {
  userId: UUID;
  userName: string;
  fullName: string;
  roleId: UUID;
  roleName: string;
  /** Permission codes granted by the role, sorted. */
  permissions: string[];
  /** Id of the location (warehouse or store) the user is assigned to, or null if they have none. */
  locationId: UUID | null;
}