"use client";

import { useEffect, useId, useState, type FormEvent } from "react";
import Button from "@/components/ui/Button";
import Drawer from "@/components/ui/Drawer";
import FormField from "@/components/ui/FormField";
import Input from "@/components/ui/Input";
import { getErrorMessage, isApiError } from "@/lib/api/api-error";
import { UNIT_NAME_MAX_LENGTH, type Unit } from "@/types/product/unit";
import type { CreateUnitRequest, UpdateUnitRequest } from "@/types/product/unit-dto";

type UnitDrawerProps = {
  open: boolean;
  /** Must be a stable function (useCallback): Drawer re-focuses its close button whenever this changes. */
  onClose: () => void;
  /** The unit being renamed, or null to create a new one. */
  unit: Unit | null;
  /** Should reject on failure; the error is shown in the form. */
  onCreate?: (request: CreateUnitRequest) => Promise<unknown>;
  /** Should reject on failure; the error is shown in the form. */
  onUpdate: (unitId: string, request: UpdateUnitRequest) => Promise<unknown>;
};

type Field = "name";
type Errors = Partial<Record<Field | "form", string>>;

export default function UnitDrawer({ open, onClose, unit, onCreate, onUpdate }: UnitDrawerProps) {
  const formId = useId();
  const [name, setName] = useState("");
  const [errors, setErrors] = useState<Errors>({});
  const [submitting, setSubmitting] = useState(false);

  const isEdit = unit !== null;

  useEffect(() => {
    setName(open ? (unit?.name ?? "") : "");
    setErrors({});
    setSubmitting(false);
  }, [open, unit]);

  async function handleSubmit(e: FormEvent) {
    e.preventDefault();

    const trimmedName = name.trim();

    const next: Errors = {};
    if (!trimmedName) next.name = "Enter the unit name.";
    setErrors(next);
    if (Object.keys(next).length > 0) return;

    setSubmitting(true);
    try {
      if (unit) {
        // Only the name can change, and only when it actually changed.
        if (trimmedName !== unit.name) await onUpdate(unit.id, { unitName: trimmedName });
      } else {
        // The code is generated by the server (U0001, U0002...).
        await onCreate?.({ unitName: trimmedName });
      }
      onClose();
    } catch (error) {
      if (isApiError(error) && error.isValidation) {
        setErrors({
          name: error.fieldError("unitName"),
          form: error.message,
        });
      } else {
        // A 409 (the name is already used) lands here with its message.
        setErrors({ form: getErrorMessage(error, "Could not save the unit.") });
      }
    } finally {
      setSubmitting(false);
    }
  }

  const nameId = `${formId}-name`;
  const codeId = `${formId}-code`;

  return (
    <Drawer
      open={open}
      onClose={onClose}
      title={isEdit ? "Rename unit" : "New unit"}
      footer={
        <div className="flex justify-end gap-2">
          <Button variant="secondary" onClick={onClose} disabled={submitting}>
            Cancel
          </Button>
          <Button type="submit" form={formId} loading={submitting}>
            {isEdit ? "Save changes" : "Create unit"}
          </Button>
        </div>
      }
    >
      <form id={formId} onSubmit={handleSubmit} noValidate className="flex flex-col gap-4">
        <FormField id={nameId} label="Name" error={errors.name} hint="For example Piece, Carton or Kilogram.">
          <Input
            id={nameId}
            value={name}
            onChange={(e) => setName(e.target.value)}
            autoComplete="off"
            maxLength={UNIT_NAME_MAX_LENGTH}
            invalid={!!errors.name}
            aria-describedby={errors.name ? `${nameId}-error` : undefined}
          />
        </FormField>

        {/* The code is generated when the unit is created; it is only shown, never typed. */}
        {unit && (
          <FormField id={codeId} label="Code" hint="Generated automatically. It cannot be changed.">
            <Input id={codeId} value={unit.code} readOnly disabled />
          </FormField>
        )}

        {errors.form && (
          <p role="alert" className="text-sm text-red-600">
            {errors.form}
          </p>
        )}
      </form>
    </Drawer>
  );
}