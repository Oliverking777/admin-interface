"use client";

import { useEffect, useId, useState, type FormEvent, type ReactNode } from "react";
import Button from "@/components/ui/Button";
import Drawer from "@/components/ui/Drawer";
import Input, { inputBaseClass } from "@/components/ui/Input";
import Select from "@/components/ui/Select";
import { getErrorMessage, isApiError } from "@/lib/api/api-error";
import { cn } from "@/lib/cn";
import {
  LOCATION_ADDRESS_MAX_LENGTH,
  LOCATION_NAME_MAX_LENGTH,
  type Location,
  type LocationType,
} from "@/types/business/location";
import type { CreateLocationRequest, UpdateLocationRequest } from "@/types/business/location-dto";

type LocationDrawerProps = {
  open: boolean;
  /** Must be a stable function (useCallback): Drawer re-focuses its close button whenever this changes. */
  onClose: () => void;
  /** The location being edited, or null to create a new one. */
  location: Location | null;
  /** Needed to create. Should reject on failure; the error is shown in the form. */
  onCreate?: (request: CreateLocationRequest) => Promise<unknown>;
  /** Should reject on failure; the error is shown in the form. */
  onUpdate: (locationId: string, request: UpdateLocationRequest) => Promise<unknown>;
};

type Field = "name" | "locationType" | "address";
type Errors = Partial<Record<Field | "form", string>>;

function FormField({
  id,
  label,
  error,
  hint,
  children,
}: {
  id: string;
  label: string;
  error?: string;
  hint?: string;
  children: ReactNode;
}) {
  return (
    <div className="flex flex-col gap-1.5">
      <label htmlFor={id} className="text-sm font-medium text-foreground">
        {label}
      </label>
      {children}
      {hint && !error && <p className="text-sm text-muted-foreground">{hint}</p>}
      {error && (
        <p id={`${id}-error`} role="alert" className="text-sm text-red-600">
          {error}
        </p>
      )}
    </div>
  );
}

export default function LocationDrawer({ open, onClose, location, onCreate, onUpdate }: LocationDrawerProps) {
  const formId = useId();
  const [name, setName] = useState("");
  const [type, setType] = useState<LocationType | "">("");
  const [address, setAddress] = useState("");
  const [errors, setErrors] = useState<Errors>({});
  const [submitting, setSubmitting] = useState(false);

  const isEdit = location !== null;

  // Fill the form when the drawer opens (with the location's values when editing); start fresh when it closes.
  useEffect(() => {
    setName(open ? (location?.name ?? "") : "");
    setType(open ? (location?.type ?? "") : "");
    setAddress(open ? (location?.address ?? "") : "");
    setErrors({});
    setSubmitting(false);
  }, [open, location]);

  async function handleSubmit(e: FormEvent) {
    e.preventDefault();

    const trimmedName = name.trim();
    const trimmedAddress = address.trim();

    const next: Errors = {};
    if (!trimmedName) next.name = "Enter the location name.";
    if (!type) next.locationType = "Choose a type.";
    setErrors(next);
    if (Object.keys(next).length > 0 || !type) return;

    setSubmitting(true);
    try {
      if (location) {
        // Send only what changed. The code can never be changed. An empty address removes it.
        const request: UpdateLocationRequest = {};
        if (trimmedName !== location.name) request.name = trimmedName;
        if (type !== location.type) request.locationType = type;
        if (trimmedAddress !== (location.address ?? "")) request.address = trimmedAddress;

        if (Object.keys(request).length > 0) await onUpdate(location.id, request);
      } else {
        // The code is generated by the server (LOC-0001, LOC-0002...). An empty address is saved as "no address".
        await onCreate?.({
          name: trimmedName,
          locationType: type,
          address: trimmedAddress,
        });
      }
      onClose();
    } catch (error) {
      if (isApiError(error) && error.isValidation) {
        setErrors({
          name: error.fieldError("name"),
          locationType: error.fieldError("locationType"),
          address: error.fieldError("address"),
          form: error.message,
        });
      } else {
        setErrors({ form: getErrorMessage(error, "Could not save the location.") });
      }
    } finally {
      setSubmitting(false);
    }
  }

  const nameId = `${formId}-name`;
  const codeId = `${formId}-code`;
  const typeId = `${formId}-type`;
  const addressId = `${formId}-address`;

  return (
    <Drawer
      open={open}
      onClose={onClose}
      title={isEdit ? "Edit location" : "New location"}
      footer={
        <div className="flex justify-end gap-2">
          <Button variant="secondary" onClick={onClose} disabled={submitting}>
            Cancel
          </Button>
          <Button type="submit" form={formId} loading={submitting}>
            {isEdit ? "Save changes" : "Create location"}
          </Button>
        </div>
      }
    >
      <form id={formId} onSubmit={handleSubmit} noValidate className="flex flex-col gap-4">
        <FormField id={nameId} label="Name" error={errors.name}>
          <Input
            id={nameId}
            value={name}
            onChange={(e) => setName(e.target.value)}
            autoComplete="off"
            maxLength={LOCATION_NAME_MAX_LENGTH}
            invalid={!!errors.name}
            aria-describedby={errors.name ? `${nameId}-error` : undefined}
          />
        </FormField>

        {/* The code is generated when the location is created; it is only shown, never typed. */}
        {location && (
          <FormField id={codeId} label="Code" hint="Generated automatically. It cannot be changed.">
            <Input id={codeId} value={location.code} readOnly disabled />
          </FormField>
        )}

        <FormField id={typeId} label="Type" error={errors.locationType}>
          <Select
            id={typeId}
            value={type}
            onChange={(e) => setType(e.target.value as LocationType | "")}
            invalid={!!errors.locationType}
            aria-describedby={errors.locationType ? `${typeId}-error` : undefined}
          >
            <option value="">Select a type</option>
            <option value="WAREHOUSE">Warehouse</option>
            <option value="STORE">Store</option>
          </Select>
        </FormField>

        <FormField
          id={addressId}
          label="Address (optional)"
          error={errors.address}
          hint={`${address.length}/${LOCATION_ADDRESS_MAX_LENGTH} characters`}
        >
          <textarea
            id={addressId}
            value={address}
            onChange={(e) => setAddress(e.target.value)}
            rows={3}
            maxLength={LOCATION_ADDRESS_MAX_LENGTH}
            aria-invalid={!!errors.address || undefined}
            aria-describedby={errors.address ? `${addressId}-error` : undefined}
            className={cn(
              inputBaseClass,
              "resize-y",
              errors.address && "border-red-600 focus:border-red-600 focus:ring-red-600/30",
            )}
          />
        </FormField>

        {errors.form && (
          <p role="alert" className="text-sm text-red-600">
            {errors.form}
          </p>
        )}
      </form>
    </Drawer>
  );
}